import { it, expect } from 'vitest';
import http from 'node:http';
import https from 'node:https';
import net from 'node:net';
import tls from 'node:tls';
import crypto from 'node:crypto';
import axios from 'axios';
it('denies transports and native business crypto with deterministic UUID/hash substitutes', async () => {
  const denied = /R539_NETWORK_DENIED/;
  expect(() => http.request('https://never.example.test')).toThrow(denied);
  expect(() => https.get('https://never.example.test')).toThrow(denied);
  expect(() => net.connect(443, 'never.example.test')).toThrow(denied);
  expect(() => new net.Socket().connect(443, 'never.example.test')).toThrow(denied);
  expect(() => tls.connect(443, 'never.example.test')).toThrow(denied);
  expect(() => fetch('https://never.example.test')).toThrow(denied);
  expect(() => new XMLHttpRequest()).toThrow(denied);
  expect(() => new WebSocket('wss://never.example.test')).toThrow(denied);
  await expect(axios.get('https://never.example.test')).rejects.toThrow(denied);
  expect(() => crypto.createHash('sha256')).toThrow(denied);
  expect(() => crypto.randomBytes(32)).toThrow(denied);
  expect(crypto.randomUUID()).toBe('11111111-1111-4111-8111-111111111111');
  expect(() => globalThis.crypto.subtle.digest('SHA-256', new Uint8Array())).toThrow(denied);
  const { sha256 } = await import('@noble/hashes/sha2.js');
  expect(sha256(new Uint8Array([1,2,3]))).toEqual(sha256(new Uint8Array([1,2,3])));
});
