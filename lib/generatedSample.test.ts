import { describe, expect, it } from 'vitest';
import { generatedSampleState, sampleStandardDocument, STANDARD_DOCUMENTS, SAMPLE_COPY, SAMPLE_DATA_COPY, SAMPLE_MODEL_COPY, SAMPLE_STANDARD_COPY } from './generatedSample';
import { sampleFixture } from '@/tests/generatedSampleFixture';

describe('generated sample public response contract', () => {
  it('pins the accepted fixed truthful text', () => {
    expect(SAMPLE_COPY).toBe('SAMPLE — generated marketplace example. Display only; not for sale. No dataset, model, download or live API service is supplied.');
    expect(SAMPLE_DATA_COPY).toBe('Illustrative listing content generated by us; this is not actual patient, clinical trial, supply chain or industrial sensor data.');
    expect(SAMPLE_MODEL_COPY).toBe("Illustrative marketplace listing; no access to GPT-4o, SDXL, Whisper or another vendor's models/services is included.");
    expect(SAMPLE_STANDARD_COPY).toBe('Standard — illustrative listing content only (document reference; no purchase contract created)');
  });
  it('accepts the safe projection and the exact controlled v1 stored marker when present', () => {
    expect(generatedSampleState(sampleFixture())).toBe('sample');
    expect(generatedSampleState(sampleFixture({structured_metadata: {generated_sample: {version: 1, mode: 'display_only'}}}))).toBe('sample');
  });
  it.each([null, false, undefined, {}, [], {version: 2, mode: 'display_only'},
    {version: true, mode: 'display_only'}, {version: 1, mode: 'sell'},
    {version: 1, mode: 'display_only', extra: true}].map(marker => ({marker})))('closes malformed raw key presence %j even with an apparently valid projection', ({marker}) => {
    expect(generatedSampleState(sampleFixture({structured_metadata: {generated_sample: marker}}))).toBe('unavailable');
  });
  it.each([null, false, undefined, {}, [], {label: 'sample', display_only: true},
    {label: 'SAMPLE', display_only: false}, {label: 'SAMPLE', display_only: true, version: 2},
    {version: 1, mode: 'display_only'}].map(generated_sample => ({generated_sample})))('does not treat raw or malformed public marker %j as a valid assertion', ({generated_sample}) => {
    expect(generatedSampleState(sampleFixture({generated_sample, purchase_hold_reason: null, purchasable: true}))).toBe('unavailable');
  });
  it.each([
    {purchasable: true}, {purchase_hold_reason: null},
    {purchase_hold_reason: 'pending_seller_terms'}, {purchase_hold_reason: 'stripe_not_ready'},
    {availability: 'available'}, {fulfillment_method: 'download'},
    {public_reference: {}}, {structured_metadata: {public_reference: null}},
  ])('closes contradictory state %j', fields => {
    expect(generatedSampleState(sampleFixture(fields))).toBe('unavailable');
  });
  it('closes a stable sample hold even without a marker', () => {
    const listing = sampleFixture(); delete listing.generated_sample;
    expect(generatedSampleState(listing)).toBe('unavailable');
  });
  it.each([0, 75])('does not infer samples from price %s, legacy fulfillment or another hold', price => {
    const listing = sampleFixture({pricing: {price}, fulfillment_type: 'reference', purchase_hold_reason: 'public_source_reference', public_reference: {label: 'Actual reference'}});
    delete listing.generated_sample;
    expect(generatedSampleState(listing)).toBe('ordinary');
  });
  it.each([true, false])('reuses only a matching existing Standard tuple/link (%s)', ai_training => {
    const url = STANDARD_DOCUMENTS[ai_training ? 0 : 1];
    const license = {code: 'standard', version: '1.0', params: {ai_training}, full_text_url: url};
    expect(sampleStandardDocument(license)).toBe(url);
    expect(sampleStandardDocument({...license, full_text_url: url.replace('https://ai.market', '')})).toBe(url);
    expect(sampleStandardDocument({...license, params: {ai_training, source_sha256: 'unexpected'}})).toBeNull();
    expect(sampleStandardDocument({...license, full_text_url: 'https://evil.example/licenses/standard/1.0/ai-training'})).toBeNull();
    expect(sampleStandardDocument({...license, version: '2.0'})).toBeNull();
    expect(sampleStandardDocument({...license, params: {ai_training: 'true'}})).toBeNull();
    expect(sampleStandardDocument({...license, code: 'custom'})).toBeNull();
  });
});
