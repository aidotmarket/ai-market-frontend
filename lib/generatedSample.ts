import type { GeneratedSampleFields } from '@/types';

export const SAMPLE_COPY = 'SAMPLE — generated marketplace example. Display only; not for sale. No dataset, model, download or live API service is supplied.';
export const SAMPLE_DATA_COPY = 'Illustrative listing content generated by us; this is not actual patient, clinical trial, supply chain or industrial sensor data.';
export const SAMPLE_MODEL_COPY = "Illustrative marketplace listing; no access to GPT-4o, SDXL, Whisper or another vendor's models/services is included.";
export const SAMPLE_UNAVAILABLE_COPY = 'This listing is unavailable. No dataset, model, download or live API service is supplied.';
export const SAMPLE_STANDARD_COPY = 'Standard — illustrative listing content only (document reference; no purchase contract created)';
export const STANDARD_DOCUMENTS = [
  'https://ai.market/licenses/standard/1.0/ai-training',
  'https://ai.market/licenses/standard/1.0/no-ai-training',
] as const;
const HOLD = 'generated_sample_display_only';
const record = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);
const has = (value: object, key: string) => Object.prototype.hasOwnProperty.call(value, key);

export type SampleState = 'ordinary' | 'sample' | 'unavailable';
/** Presence closes presentation before validation. Only the safe API projection,
 * paired with the stable closed hold, authorizes the SAMPLE assertion. The
 * producing backend must validate stored {version:1,mode:'display_only'}.
 * Ordinary responses must omit generated_sample, rather than emit null. */
export function generatedSampleState(value: unknown): SampleState {
  if (!record(value)) return 'ordinary';
  const raw = record(value.structured_metadata) ? value.structured_metadata : null;
  const present = has(value, 'generated_sample') || !!(raw && has(raw, 'generated_sample'));
  if (!present && value.purchase_hold_reason !== HOLD) return 'ordinary';
  const marker = value.generated_sample;
  if (!record(marker) || Object.keys(marker).length !== 2 || marker.label !== 'SAMPLE' || marker.display_only !== true ||
      value.purchasable !== false || value.purchase_hold_reason !== HOLD ||
      (has(value, 'availability') && value.availability !== 'display_only') ||
      (has(value, 'fulfillment_method') && value.fulfillment_method !== 'none') ||
      value.public_reference != null || (raw && has(raw, 'public_reference'))) return 'unavailable';
  // Raw metadata is not expected publicly; if supplied, never bless an invalid
  // stored marker simply because the accompanying projection looks valid.
  if (raw && has(raw, 'generated_sample')) {
    const stored = raw.generated_sample;
    if (!record(stored) || Object.keys(stored).length !== 2 || stored.version !== 1 || stored.mode !== 'display_only') return 'unavailable';
  }
  return 'sample';
}

export function samplePresentation(value: { title?: string | null } & GeneratedSampleFields) {
  const state = generatedSampleState(value);
  return {
    state,
    title: `${state === 'sample' ? 'SAMPLE' : 'Unavailable'} — ${value.title || 'Listing'}`,
    description: state === 'sample' ? SAMPLE_COPY : SAMPLE_UNAVAILABLE_COPY,
  };
}

/** Existing canonical document links only; never reuse buyer summaries or infer
 * a contractual variant from retained JSON-LD. Saved tuple reconciliation and
 * hash validation remain backend responsibilities. */
export function sampleStandardDocument(license: unknown): string | null {
  if (!record(license) || license.code !== 'standard' || license.version !== '1.0' ||
      !record(license.params) || Object.keys(license.params).length !== 1 || typeof license.params.ai_training !== 'boolean') return null;
  const expected = STANDARD_DOCUMENTS[license.params.ai_training ? 0 : 1];
  return license.full_text_url === expected || license.full_text_url === expected.replace('https://ai.market', '') ? expected : null;
}
